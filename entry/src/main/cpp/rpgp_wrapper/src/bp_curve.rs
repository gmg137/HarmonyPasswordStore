//! brainpool 曲线算术（GnuPG `ky768_bp256` / `ky1024_bp384` 的经典部分）
//!
//! ## 为什么自己实现
//!
//! RustCrypto 的 `bp256`/`bp384` **只有曲线参数、没有算术实现**（无 `arithmetic`
//! feature），fiat-crypto 也不含 brainpool，`primefield` 又只配 ff 0.14/crypto-bigint
//! 0.7（与 `elliptic-curve` 0.13 的 ff 0.13/crypto-bigint 0.5 冲突）。而
//! `elliptic-curve` 的 `CurveArithmetic::Scalar` 需要 `Reduce`/`IsHigh`/
//! `ScalarPrimitive` 转换等一整套约束，为两条曲线补齐并不划算。
//!
//! ## 实现方式（复用已验证组件，不发明密码学）
//!
//! - **素域**：Montgomery 形式。归约用 `crypto-bigint` 的
//!   `const fn montgomery_reduction`，加减负用 `add_mod`/`sub_mod`/`neg_mod`，
//!   求逆用常数时间的 `inv_mod`（Bernstein-Yang）。这些都是 RustCrypto 已审计的
//!   代码，本模块只提供各曲线的模数、`-p⁻¹ mod 2^64` 与 `R²`。
//! - **点运算**：Renes-Costello-Batina 2015 **完备加法公式**（Algorithm 1，
//!   对任意 a 成立）。完备公式无例外情形（无穷远点、倍点、互逆点都能正确相加），
//!   故 `double(P) = add(P, P)`，标量乘用 Montgomery ladder 即常数时间完成，
//!   无需分支处理边界。公式逐行对照 `primeorder` 的 `EquationAIsGeneric` 转写。
//!
//! ## 验证（tests，三层缺一不可）
//!
//! 1. 素域算术与 Python 大整数对拍
//! 2. **标量乘与 RFC 5639 附录 A 官方向量对拍**（k·G 的坐标）
//! 3. 与本地 gpg 双向互操作（真实密钥 + 真实密文）
//!
//! 只做第 3 层不够：互操作失败无法区分「曲线算错」与「KDF/编码错」；
//! 第 1、2 层能精确锁定算术本身。

use elliptic_curve::bigint::modular::montgomery_reduction;
use elliptic_curve::bigint::{Encoding, Limb, U256, U384};
use elliptic_curve::subtle::ConstantTimeEq;

/// 生成一条 brainpool 曲线的素域 + 点运算
///
/// 参数：域元素类型名、点类型名、底层整数类型、字节长度、模数、`-p⁻¹ mod 2^64`、
/// `R²`、曲线系数 a/b、生成元 Gx/Gy
macro_rules! impl_brainpool_curve {
    (
        $fe:ident, $pt:ident, $uint:ty, $len:expr,
        $modulus:expr, $mod_neg_inv:expr, $r2:expr,
        $ca:expr, $cb:expr, $gx:expr, $gy:expr
    ) => {
        /// 素域元素（内部为 Montgomery 形式）
        #[derive(Clone, Copy, Debug)]
        pub struct $fe(pub(crate) $uint);

        impl $fe {
            pub const ZERO: $fe = $fe(<$uint>::ZERO);
            /// 1 的 Montgomery 形式是 R mod p（**不是 R²**）。
            /// 曾误写成 R²，导致无穷远点的 y 坐标错误、凡与无穷远点相加都算错
            /// （表现为 k=1 得不到 G，而单点运算与域运算看起来都正常）。
            pub const ONE: $fe = $fe(Self::to_mont(<$uint>::ONE));
            /// 曲线系数 a
            pub const A: $fe = $fe(Self::to_mont($ca));
            /// 曲线系数 b
            pub const B: $fe = $fe(Self::to_mont($cb));
            /// 完备加法公式用的 3b
            pub const B3: $fe = $fe::from_u64(3).mul(&Self::B);
            /// 生成元 X
            pub const GX: $fe = $fe(Self::to_mont($gx));
            /// 生成元 Y
            pub const GY: $fe = $fe(Self::to_mont($gy));

            /// 转入 Montgomery 形式：w · R² · R⁻¹ = wR
            #[inline]
            const fn to_mont(w: $uint) -> $uint {
                let (lo, hi) = w.mul_wide(&$r2);
                montgomery_reduction(&(lo, hi), &$modulus, $mod_neg_inv)
            }

            /// 转出 Montgomery 形式
            #[inline]
            const fn from_mont(w: $uint) -> $uint {
                montgomery_reduction(&(w, <$uint>::ZERO), &$modulus, $mod_neg_inv)
            }

            #[inline]
            pub const fn from_u64(v: u64) -> Self {
                $fe(Self::to_mont(<$uint>::from_u64(v)))
            }

            /// 从大端字节解析（须 < p）
            pub fn from_be_bytes(b: &[u8]) -> Result<Self, String> {
                if b.len() != $len {
                    return Err(format!("域元素长度应为 {}，实际 {}", $len, b.len()));
                }
                let mut arr = [0u8; $len];
                arr.copy_from_slice(b);
                let v = <$uint>::from_be_slice(&arr);
                if v >= $modulus {
                    return Err("域元素超出模数".into());
                }
                Ok($fe(Self::to_mont(v)))
            }

            /// 转回大端字节（定长）
            pub fn to_be_bytes(self) -> Vec<u8> {
                Self::from_mont(self.0).to_be_bytes().to_vec()
            }

            #[inline]
            pub const fn add(&self, o: &Self) -> Self {
                $fe(self.0.add_mod(&o.0, &$modulus))
            }

            #[inline]
            pub const fn sub(&self, o: &Self) -> Self {
                $fe(self.0.sub_mod(&o.0, &$modulus))
            }

            #[inline]
            pub const fn mul(&self, o: &Self) -> Self {
                let (lo, hi) = self.0.mul_wide(&o.0);
                $fe(montgomery_reduction(&(lo, hi), &$modulus, $mod_neg_inv))
            }

            #[inline]
            pub const fn square(&self) -> Self {
                let (lo, hi) = self.0.square_wide();
                $fe(montgomery_reduction(&(lo, hi), &$modulus, $mod_neg_inv))
            }

            #[inline]
            pub const fn neg(&self) -> Self {
                $fe(self.0.neg_mod(&$modulus))
            }

            /// 常数时间求逆（Bernstein-Yang）
            ///
            /// **必须先转出 Montgomery 形式再求逆**：`inv_mod` 算的是它拿到那个整数
            /// 的逆元，直接对 Montgomery 形式 `aR` 求逆得到的是 `a⁻¹R⁻¹`，
            /// 不是 Montgomery 形式的 `a⁻¹R`。曾漏掉这一步，表现为
            /// 「点在曲线上、域运算自洽，但仿射编码全错」（Z 坐标归一化用了错的逆）。
            pub fn invert(&self) -> Result<Self, String> {
                let plain = Self::from_mont(self.0);
                let (inv, ok) = plain.inv_mod(&$modulus);
                if bool::from(ok) {
                    Ok($fe(Self::to_mont(inv)))
                } else {
                    Err("域元素不可逆（零元）".into())
                }
            }

            #[inline]
            pub fn is_zero(&self) -> bool {
                self.0 == <$uint>::ZERO
            }

            #[inline]
            pub fn ct_eq(&self, o: &Self) -> bool {
                bool::from(ConstantTimeEq::ct_eq(&self.0, &o.0))
            }

            /// 常数时间选择（Montgomery ladder 用）
            #[inline]
            pub fn ct_select(a: &Self, b: &Self, choice: u8) -> Self {
                use elliptic_curve::subtle::{Choice, ConditionallySelectable};
                $fe(<$uint>::conditional_select(&a.0, &b.0, Choice::from(choice)))
            }
        }

        /// 投影坐标点 `(X : Y : Z)`，`Z = 0` 表示无穷远点
        #[derive(Clone, Copy, Debug)]
        pub struct $pt {
            pub x: $fe,
            pub y: $fe,
            pub z: $fe,
        }

        impl $pt {
            pub const IDENTITY: $pt = $pt {
                x: $fe::ZERO,
                y: $fe::ONE,
                z: $fe::ZERO,
            };

            #[inline]
            pub fn from_affine(x: $fe, y: $fe) -> Self {
                $pt { x, y, z: $fe::ONE }
            }

            #[inline]
            pub fn is_identity(&self) -> bool {
                self.z.is_zero()
            }

            /// 生成元
            #[inline]
            pub fn generator() -> Self {
                $pt::from_affine($fe::GX, $fe::GY)
            }

            /// 完备加法（Renes-Costello-Batina 2015, Algorithm 1，任意 a 成立）
            ///
            /// 逐行对照 `primeorder::point_arithmetic::EquationAIsGeneric::add` 转写，
            /// 行末编号即论文算法步骤。完备性保证无穷远点、倍点、互逆点都无需分支，
            /// 因此可直接用于常数时间 ladder。
            pub fn add(&self, rhs: &Self) -> Self {
                let a = $fe::A;
                let b3 = $fe::B3;

                let t0 = self.x.mul(&rhs.x); // 1
                let t1 = self.y.mul(&rhs.y); // 2
                let t2 = self.z.mul(&rhs.z); // 3
                let t3 = self.x.add(&self.y); // 4
                let t4 = rhs.x.add(&rhs.y); // 5
                let t3 = t3.mul(&t4); // 6
                let t4 = t0.add(&t1); // 7
                let t3 = t3.sub(&t4); // 8
                let t4 = self.x.add(&self.z); // 9
                let t5 = rhs.x.add(&rhs.z); // 10
                let t4 = t4.mul(&t5); // 11
                let t5 = t0.add(&t2); // 12
                let t4 = t4.sub(&t5); // 13
                let t5 = self.y.add(&self.z); // 14
                let x3 = rhs.y.add(&rhs.z); // 15
                let t5 = t5.mul(&x3); // 16
                let x3 = t1.add(&t2); // 17
                let t5 = t5.sub(&x3); // 18
                let z3 = a.mul(&t4); // 19
                let x3 = b3.mul(&t2); // 20
                let z3 = x3.add(&z3); // 21
                let x3 = t1.sub(&z3); // 22
                let z3 = t1.add(&z3); // 23
                let y3 = x3.mul(&z3); // 24
                let t1 = t0.add(&t0); // 25
                let t1 = t1.add(&t0); // 26
                let t2 = a.mul(&t2); // 27
                let t4 = b3.mul(&t4); // 28
                let t1 = t1.add(&t2); // 29
                let t2 = t0.sub(&t2); // 30
                let t2 = a.mul(&t2); // 31
                let t4 = t4.add(&t2); // 32
                let t0 = t1.mul(&t4); // 33
                let y3 = y3.add(&t0); // 34
                let t0 = t5.mul(&t4); // 35
                let x3 = t3.mul(&x3); // 36
                let x3 = x3.sub(&t0); // 37
                let t0 = t3.mul(&t1); // 38
                let z3 = t5.mul(&z3); // 39
                let z3 = z3.add(&t0); // 40

                $pt { x: x3, y: y3, z: z3 }
            }

            /// 倍点：完备公式下 `2P = P + P`
            #[inline]
            pub fn double(&self) -> Self {
                self.add(self)
            }

            #[inline]
            pub fn ct_select(a: &Self, b: &Self, choice: u8) -> Self {
                $pt {
                    x: $fe::ct_select(&a.x, &b.x, choice),
                    y: $fe::ct_select(&a.y, &b.y, choice),
                    z: $fe::ct_select(&a.z, &b.z, choice),
                }
            }

        /// 常数时间标量乘（Montgomery ladder）
        ///
        /// 不变量：处理完前缀 m 后 `R0 = m·P`、`R1 = (m+1)·P`。
        /// 用条件交换代替分支，配合完备加法公式即全程无分支。
        /// 标量按大端逐位处理；不要求 `d < n`——P 的阶为 n，
        /// 故 d ≥ n 时结果自动等价于 `d mod n`。
        pub fn ladder(pt: &$pt, d_be: &[u8]) -> $pt {
            let mut r0 = $pt::IDENTITY;
            let mut r1 = *pt;
            for byte in d_be {
                for i in (0..8).rev() {
                    let bit = (byte >> i) & 1;
                    let a = $pt::ct_select(&r0, &r1, bit);
                    let b = $pt::ct_select(&r1, &r0, bit);
                    let sum = a.add(&b);
                    let dbl = a.double();
                    r0 = $pt::ct_select(&dbl, &sum, bit);
                    r1 = $pt::ct_select(&sum, &dbl, bit);
                }
            }
            r0
        }
            /// 转仿射并编码为未压缩点 `0x04 || X || Y`
            pub fn to_encoded(&self) -> Result<Vec<u8>, String> {
                if self.is_identity() {
                    return Err("结果为无穷远点".into());
                }
                // **齐次投影坐标**：x = X/Z、y = Y/Z。
                // 注意不是 Jacobian 的 X/Z²、Y/Z³——RC-B 的完备加法公式用的是齐次投影，
                // 混用会在 Z≠1 时把点编码错（Z=1 时两者巧合相同，故单点测试看不出来）。
                let zinv = self.z.invert()?;
                let x = self.x.mul(&zinv);
                let y = self.y.mul(&zinv);
                let mut out = Vec::with_capacity(1 + 2 * $len);
                out.push(0x04);
                out.extend_from_slice(&x.to_be_bytes());
                out.extend_from_slice(&y.to_be_bytes());
                Ok(out)
            }

            /// 解码未压缩点并校验在曲线上
            ///
            /// 校验不可省：`ecc_ct` 来自密文（同步下来的仓库内容，攻击者可控），
            /// 曲线外的点会让 ECDH 结果可被操纵。
            pub fn from_encoded(enc: &[u8]) -> Result<Self, String> {
                if enc.len() != 1 + 2 * $len || enc[0] != 0x04 {
                    return Err(format!("点编码非法（应为 {} 字节未压缩点）", 1 + 2 * $len));
                }
                let x = $fe::from_be_bytes(&enc[1..1 + $len])?;
                let y = $fe::from_be_bytes(&enc[1 + $len..])?;
                // y² == x³ + ax + b
                let lhs = y.square();
                let rhs = x.square().mul(&x).add(&$fe::A.mul(&x)).add(&$fe::B);
                if !lhs.ct_eq(&rhs) {
                    return Err("公钥点不在曲线上".into());
                }
                Ok($pt::from_affine(x, y))
            }
        }

    };
}

