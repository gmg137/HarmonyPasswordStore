/// 曲线族（供 gpg_pqc 按曲线名分发）
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WeierstrassCurve {
    Bp256,
    Bp384,
}

impl WeierstrassCurve {
    /// 未压缩点编码长度
    pub fn point_len(self) -> usize {
        match self {
            WeierstrassCurve::Bp256 => 65,
            WeierstrassCurve::Bp384 => 97,
        }
    }

    /// 私钥标量长度
    pub fn scalar_len(self) -> usize {
        match self {
            WeierstrassCurve::Bp256 => 32,
            WeierstrassCurve::Bp384 => 48,
        }
    }
}

/// 标量乘：返回 `d · P` 的未压缩点编码（`0x04 || X || Y`）
///
/// 口径与 GnuPG `gcry_kem_decap` 一致：composite KEM 把该点**整体**交给
/// `gnupg_ecc_kem_simple_kdf`，**不取 x 坐标**（x 坐标截断只属于普通 ECDH，algo 18）。
pub fn scalar_mul(
    curve: WeierstrassCurve,
    d_be: &[u8],
    peer_point: &[u8],
) -> Result<Vec<u8>, String> {
    match curve {
        WeierstrassCurve::Bp256 => {
            let pt = Bp256Point::from_encoded(peer_point)?;
            Bp256Point::ladder(&pt, d_be).to_encoded()
        }
        WeierstrassCurve::Bp384 => {
            let pt = Bp384Point::from_encoded(peer_point)?;
            Bp384Point::ladder(&pt, d_be).to_encoded()
        }
    }
}

/// 生成临时密钥对并算共享点：返回 `(临时公钥点, 共享点)`（均为未压缩编码）
///
/// `scalar_be` 为临时私钥标量（调用方提供随机数）
pub fn ephemeral(
    curve: WeierstrassCurve,
    scalar_be: &[u8],
    peer_point: &[u8],
) -> Result<(Vec<u8>, Vec<u8>), String> {
    match curve {
        WeierstrassCurve::Bp256 => {
            let peer = Bp256Point::from_encoded(peer_point)?;
            let ct = Bp256Point::ladder(&Bp256Point::generator(), scalar_be).to_encoded()?;
            let shared = Bp256Point::ladder(&peer, scalar_be).to_encoded()?;
            Ok((ct, shared))
        }
        WeierstrassCurve::Bp384 => {
            let peer = Bp384Point::from_encoded(peer_point)?;
            let ct = Bp384Point::ladder(&Bp384Point::generator(), scalar_be).to_encoded()?;
            let shared = Bp384Point::ladder(&peer, scalar_be).to_encoded()?;
            Ok((ct, shared))
        }
    }
}

